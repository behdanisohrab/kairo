const Ctx = createContext<I18nCtx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('kairo-lang') as Lang | null
    if (saved === 'fa' || saved === 'en') return saved
    if (navigator.language.startsWith('fa')) return 'fa'
    return 'en'
  })

  const setLang = (l: Lang) => {
    setLangState(l)
    localStorage.setItem('kairo-lang', l)
  }

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr'
    if (lang === 'fa') {
      document.documentElement.style.setProperty('--font-body', "'Vazirmatn','Outfit',system-ui,sans-serif")
    } else {
      document.documentElement.style.setProperty('--font-body', "'Outfit',system-ui,sans-serif")
    }
  }, [lang])

  const t = (key: string, params?: Record<string, string | number>) => {
    const dict = dicts[lang]
    let str = dict[key] ?? dicts.en[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replaceAll(`{${k}}`, String(v))
      }
    }
    return str
  }

  return <Ctx.Provider value={{ lang, setLang, t, dir: lang === 'fa' ? 'rtl' : 'ltr' }}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n must be inside I18nProvider')
  return ctx
}
